"""
Compact receipt generator for tool results.

When a tool returns a large result, the full payload is stored on the session
filesystem and the conversation receives a compact *receipt* instead.  The
receipt contains:

1. **Preview** – the first 2-3 meaningful lines so the model has immediate
   signal.
2. **Gap analysis** – a description of what the preview does NOT cover,
   generated by a small LLM (Haiku) when available, otherwise by heuristics.

Design Principles:
- LLM-enhanced gap analysis using a small, cheap model (Haiku via Bedrock).
- Falls back to heuristic analysis if the LLM call fails or is disabled.
- Structural awareness – understands JSON objects/arrays to give richer gaps.
- Conservative – small results pass through unmodified
  (below MIN_COMPACT_SIZE).
"""

from __future__ import annotations

import asyncio
import json
import logging
import re
from dataclasses import dataclass

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Compact receipt
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class CompactReceipt:
    """Immutable compact representation of a stored tool result."""

    entry_id: str
    size_bytes: int
    preview: str
    gap: str

    def format(self) -> str:
        return (
            f"[session_fs: {self.entry_id} | {self._human_size()}]\n"
            f"Preview:\n{self.preview}\n"
            f"Gap: {self.gap}\n"
            f'Retrieve: session_grep("<pattern>") or '
            f'read_session_file("{self.entry_id}")'
        )

    def _human_size(self) -> str:
        if self.size_bytes < 1024:
            return f"{self.size_bytes} B"
        if self.size_bytes < 1024 * 1024:
            return f"{self.size_bytes / 1024:.1f} KB"
        return f"{self.size_bytes / (1024 * 1024):.1f} MB"


# ---------------------------------------------------------------------------
# Compactor
# ---------------------------------------------------------------------------

# Tools whose results should never be compacted (they are already selective).
PASSTHROUGH_TOOLS: frozenset[str] = frozenset(
    {
        "session_grep",
        "session_summary",
        "read_session_file",
        "get_current_time",
    }
)

# Results shorter than this are not worth compacting.
MIN_COMPACT_SIZE = 500

# Preview tuning
_PREVIEW_MAX_LINES = 3
_PREVIEW_MAX_CHARS = 300

# Maximum chars of the result sent to the LLM for summarisation.
_LLM_INPUT_CAP = 4000

_LLM_SYSTEM_PROMPT = (
    "You are a concise data analyst. Given a tool result, "
    "produce a 1-3 sentence gap analysis describing what "
    "information is present BEYOND the short preview shown. "
    "Focus on structure, counts, hidden fields, and any "
    "notable data the user might need to drill into. "
    "Reply with ONLY the gap analysis, no preamble."
)


class ResultCompactor:
    """Produces compact receipts from large tool results.

    When ``use_llm=True`` (the default), gap analysis is generated
    by a small Bedrock model (Haiku).  If the LLM call fails or
    ``use_llm=False``, the compactor falls back to the original
    heuristic analysis.
    """

    def __init__(self, *, use_llm: bool = True):
        self._use_llm = use_llm
        self._model = None

    def _get_model(self):
        """Lazily create a BedrockModel for the small Haiku model."""
        if self._model is None:
            try:
                from strands.models import BedrockModel

                from app.core.config import settings

                model_id = settings.bedrock.models.get(
                    "claude_haiku",
                    "anthropic.claude-haiku-4-20250514",
                )
                self._model = BedrockModel(
                    model_id=model_id,
                    region_name=settings.bedrock.region,
                )
            except Exception:
                logger.debug(
                    "Failed to create Haiku model for compaction, "
                    "falling back to heuristic"
                )
                self._use_llm = False
        return self._model

    def should_compact(self, tool_name: str, text: str) -> bool:
        """Return True if result is large enough for compaction."""
        if tool_name in PASSTHROUGH_TOOLS:
            return False
        return len(text) > MIN_COMPACT_SIZE

    def compact(self, entry_id: str, text: str) -> CompactReceipt:
        """Build a compact receipt with preview and gap analysis."""
        preview = self._extract_preview(text)
        gap = self._analyze_gap(text, preview)
        return CompactReceipt(
            entry_id=entry_id,
            size_bytes=len(text.encode("utf-8")),
            preview=preview,
            gap=gap,
        )

    async def compact_async(
        self, entry_id: str, text: str
    ) -> CompactReceipt:
        """Async version that uses LLM for gap analysis when enabled."""
        preview = self._extract_preview(text)
        gap = await self._analyze_gap_async(text, preview)
        return CompactReceipt(
            entry_id=entry_id,
            size_bytes=len(text.encode("utf-8")),
            preview=preview,
            gap=gap,
        )

    # -- preview extraction --------------------------------------------------

    @staticmethod
    def _extract_preview(text: str) -> str:
        """First 2-3 meaningful lines, capped at _PREVIEW_MAX_CHARS."""
        lines = text.split("\n")
        meaningful = [ln for ln in lines if ln.strip()][
            :_PREVIEW_MAX_LINES
        ]
        preview = "\n".join(meaningful)
        if len(preview) > _PREVIEW_MAX_CHARS:
            preview = preview[:_PREVIEW_MAX_CHARS] + "..."
        return preview

    # -- gap analysis (sync, heuristic) --------------------------------------

    def _analyze_gap(self, text: str, preview: str) -> str:
        total = len(text)
        # Strip only the truncation ellipsis, not arbitrary trailing dots
        shown = (
            len(preview[:-3]) if preview.endswith("...") else len(preview)
        )

        if total <= shown:
            return "Preview contains the complete result."

        # Attempt structured analysis first, fall back to plain-text.
        try:
            data = json.loads(text)
            hints = self._json_gap(data, preview)
        except (json.JSONDecodeError, TypeError):
            hints = self._text_gap(text, preview)

        pct = min(shown / total * 100, 100)
        hints.append(f"showing ~{pct:.0f}% of {total} chars total")
        return ". ".join(h for h in hints if h) + "."

    # -- gap analysis (async, LLM-enhanced) ----------------------------------

    async def _analyze_gap_async(
        self, text: str, preview: str
    ) -> str:
        """Try LLM gap analysis, fall back to heuristic on failure."""
        if not self._use_llm:
            return self._analyze_gap(text, preview)

        total = len(text)
        shown = (
            len(preview[:-3]) if preview.endswith("...") else len(preview)
        )
        if total <= shown:
            return "Preview contains the complete result."

        try:
            return await self._llm_gap_analysis(text, preview)
        except Exception:
            logger.debug(
                "LLM gap analysis failed, falling back to heuristic",
                exc_info=True,
            )
            return self._analyze_gap(text, preview)

    async def _llm_gap_analysis(
        self, text: str, preview: str
    ) -> str:
        """Use a small LLM to generate a gap analysis."""
        model = self._get_model()
        if model is None:
            return self._analyze_gap(text, preview)

        # Cap the input to avoid sending huge payloads
        truncated = text[:_LLM_INPUT_CAP]
        if len(text) > _LLM_INPUT_CAP:
            truncated += f"\n... ({len(text) - _LLM_INPUT_CAP} more chars)"

        user_prompt = (
            f"PREVIEW (first few lines the user sees):\n"
            f"{preview}\n\n"
            f"FULL RESULT:\n"
            f"{truncated}\n\n"
            f"Total size: {len(text)} chars. "
            f"Describe what is in the full result that the preview "
            f"does NOT show."
        )

        messages = [
            {"role": "user", "content": [{"text": user_prompt}]}
        ]

        response = await asyncio.to_thread(
            model.converse,
            messages=messages,
            system_prompt=_LLM_SYSTEM_PROMPT,
            inference_config={"maxTokens": 150, "temperature": 0.0},
        )

        # Extract text from response
        output = response.get("output", {})
        content = output.get("content", [])
        parts = []
        for block in content:
            if isinstance(block, dict) and "text" in block:
                parts.append(block["text"])
        gap_text = " ".join(parts).strip()

        if not gap_text:
            return self._analyze_gap(text, preview)

        total = len(text)
        shown = (
            len(preview[:-3])
            if preview.endswith("...")
            else len(preview)
        )
        pct = min(shown / total * 100, 100)
        return f"{gap_text} (showing ~{pct:.0f}% of {total} chars)"

    # -- JSON gap analysis ---------------------------------------------------

    @staticmethod
    def _json_gap(data: object, preview: str) -> list[str]:
        hints: list[str] = []

        if isinstance(data, dict):
            keys = list(data.keys())
            hidden = [k for k in keys if k not in preview]
            if hidden:
                sample = hidden[:8]
                label = ", ".join(sample)
                extra = (
                    f" (+{len(hidden) - 8} more)"
                    if len(hidden) > 8
                    else ""
                )
                hints.append(
                    f"JSON object with {len(keys)} keys; "
                    f"not in preview: {label}{extra}"
                )
            # Flag large nested arrays — often the most valuable data.
            for k, v in data.items():
                if isinstance(v, list) and len(v) > 2:
                    hints.append(
                        f"key '{k}' is a list with {len(v)} items"
                    )

        elif isinstance(data, list):
            hints.append(f"JSON array with {len(data)} items")

        return hints

    # -- plain-text gap analysis ---------------------------------------------

    @staticmethod
    def _text_gap(text: str, preview: str) -> list[str]:
        hints: list[str] = []

        total_lines = text.count("\n") + 1
        preview_lines = preview.count("\n") + 1
        if total_lines > preview_lines:
            hints.append(
                f"{total_lines} total lines; "
                f"preview shows first {preview_lines}"
            )

        # Surface unique capitalised terms from the hidden portion.
        hidden = text[len(preview) :]
        hidden_terms = set(
            re.findall(
                r"\b[A-Z][a-z]{2,}(?:\s[A-Z][a-z]+)*\b", hidden
            )
        )
        preview_terms = set(
            re.findall(
                r"\b[A-Z][a-z]{2,}(?:\s[A-Z][a-z]+)*\b", preview
            )
        )
        unique = hidden_terms - preview_terms
        if unique:
            sample = sorted(unique)[:6]
            hints.append(
                f"topics not in preview: {', '.join(sample)}"
            )

        return hints
